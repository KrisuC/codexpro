import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {Client} from '@modelcontextprotocol/sdk/client/index.js';
import {StdioClientTransport} from '@modelcontextprotocol/sdk/client/stdio.js';
import {timeoutFor} from '../reliability.mjs';

const directory=fs.mkdtempSync(path.join(os.tmpdir(),'codexpro-reliability-'));
const names=['read','bash','server_config','open_workspace','open_current_workspace','codexpro'];
const catalog=path.join(directory,'catalog.json');
fs.writeFileSync(catalog,JSON.stringify({tools:names.map(name=>({name,description:'Synthetic tool',inputSchema:{type:'object',properties:['read','bash'].includes(name)?{workspace_id:{type:'string'}}:{},additionalProperties:true}}))}));
const optionalCatalog=path.join(directory,'optional.json');fs.writeFileSync(optionalCatalog,JSON.stringify({tools:[]}));
const configFile=path.join(directory,'config.json');
const definition={command:process.execPath,args:[fileURLToPath(new URL('./reliability-backend.mjs',import.meta.url)),directory,'--bash','full'],catalog,cwd:directory};
fs.writeFileSync(configFile,JSON.stringify({allowedRoots:[directory],requestTimeoutMs:250,diagnosticsDir:directory,backends:{codexpro:definition,windows:{...definition,catalog:optionalCatalog,prefix:'windows_',enabled:false},playwright:{...definition,catalog:optionalCatalog,prefix:'pw_',enabled:false}}}));
const launcher=process.argv[2]??fileURLToPath(new URL('../launch-gateway.mjs',import.meta.url));
const transport=new StdioClientTransport({command:process.execPath,args:[launcher,configFile],stderr:'pipe'});
transport.stderr?.resume();
const client=new Client({name:'reliability-verification',version:'1'});
const call=(name,args={},session)=>client.callTool({name,arguments:args,...(session?{_meta:{'openai/session':session}}:{})},undefined,{timeout:15000});
const records=[];
try{
 await client.connect(transport);
 const before=(await call('server_config')).structuredContent.pid;
 const bad=await call('read',{path:'invalid'});
 assert.equal(bad.isError,true);assert.match(bad.content[0].text,/invalid_arguments/);
 assert.equal((await call('server_config')).structuredContent.pid,before);
 records.push('Invalid arguments preserve the connection and report an actionable cause');
 const [slow,parallel]=await Promise.all([call('read',{path:'slow'}),call('server_config')]);
 assert.equal(slow.isError,true);assert.match(slow.content[0].text,/timeout/);
 assert.equal(parallel.structuredContent.pid,before);
 assert.equal((await call('server_config')).structuredContent.pid,before);
 records.push('A real timeout preserves concurrent and subsequent calls');
 const long=await call('bash',{command:'slow',timeout_ms:1000});
 assert.equal(long.isError,undefined);assert.equal(long.structuredContent.exitCode,0);
 assert.equal(timeoutFor('bash',{timeout_ms:600000}),615000);
 records.push('Shell calls honor their requested execution time plus response grace');
 const unopened=await call('read',{path:'fixture'},'synthetic-new-chat');
 assert.equal(unopened.isError,true);
 await call('open_workspace',{path:'a'},'synthetic-chat-a');
 await call('codexpro',{action:'open_workspace',args:{path:'b'}},'synthetic-chat-b');
 assert.equal((await call('read',{path:'fixture'},'synthetic-chat-a')).structuredContent.workspace_id,'ws_a');
 assert.equal((await call('codexpro',{action:'read',args:{path:'fixture'}},'synthetic-chat-b')).structuredContent.workspace_id,'ws_b');
 records.push('Two conversation metadata IDs retain independent workspace selections');
 const recovered=await call('read',{path:'crash-once',workspace_id:'ws_a'});
 assert.equal(recovered.structuredContent.workspace_id,'ws_a');
 assert.notEqual(recovered.structuredContent.pid,before);
 records.push('A closed transport recovers one read-only call');
 const mutation=await call('bash',{command:'crash-mutation'});
 assert.equal(mutation.isError,true);assert.equal(fs.readFileSync(path.join(directory,'mutation-count'),'utf8'),'1');
 assert.ok((await call('server_config')).structuredContent.pid);
 records.push('A crashed mutation is not replayed; the next call reconnects');
 const actions=JSON.parse((await call('codexpro')).content[0].text);
 assert.ok(actions.actions.some(t=>t.name==='integration_status'));
 const wrapped=await call('codexpro',{action:'config'});
 assert.ok(wrapped.structuredContent.gateway);
 const schema=JSON.parse((await call('codexpro',{action:'action_schema',args:{name:'bash'}})).content[0].text);
 assert.match(schema.description,/Full shell/);assert.doesNotMatch(schema.description,/allowlisted/);
 records.push('Default/aliased wrapper actions use the gateway and truthful full-shell metadata');
 await call('read',{path:'SYNTHETIC_PRIVATE_ARGUMENT_MUST_NOT_BE_LOGGED'});
 const log=fs.readdirSync(directory).filter(f=>/^gateway-\d+\.jsonl$/.test(f)).map(f=>fs.readFileSync(path.join(directory,f),'utf8')).join('');
 assert.match(log,/call_error/);assert.doesNotMatch(log,/SYNTHETIC_PRIVATE_ARGUMENT_MUST_NOT_BE_LOGGED|synthetic-chat-a/);
 records.push('Diagnostics contain failure metadata without arguments or conversation IDs');
 console.log(JSON.stringify({passed:true,records},null,2));
}finally{
 await client.close();
 // Only remove flat files created by this test under its fresh temporary folder.
 for(const file of fs.readdirSync(directory))fs.unlinkSync(path.join(directory,file));
 fs.rmdirSync(directory);
}
